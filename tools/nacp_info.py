"""
Read the title / author / version from an NRO's embedded NACP.

This is what the Homebrew Menu (Album) displays for a .nro.

⚠️ Gotchas learned the hard way:
  - The version shown in hbmenu comes from the **NACP**, generated by the
    Makefile's APP_VERSION. It has nothing to do with any "vX.Y.Z" string
    hard-coded in the C/C++ source. Keep them in sync (or pass it via -D).
  - The NACP section inside an NRO has **no "NACP" magic header**. Byte 0 is
    already the name field. Searching for b"NACP" finds nothing.
  - The version is a plain **ASCII string** (e.g. "1.4.4") at NACP+0x3060,
    not a packed u32.

NACP layout (switch-tools nacptool output):
  0x0000  char name[0x200]
  0x0200  char author[0x100]
  ...     (remaining language entries, 16 * 0x300 total)
  0x3060  char version[0x10]      ASCII

Usage:
    python nacp_info.py <file.nro>
"""
import struct
import sys

ASET = b"ASET"


def read_nacp(path):
    d = open(path, "rb").read()

    # Locate the asset header. Modern libnx puts it at 0x10 + NroHeader.size,
    # but old NROs leave NroHeader.size = 0, so just scan for the ASET magic.
    ah = d.find(ASET)
    if ah < 0:
        raise SystemExit("ASET asset header not found - not a standard NRO?")

    _ver, _ico_off, _ico_sz, nacp_off, nacp_sz, _r_off, _r_sz = \
        struct.unpack_from("<I6Q", d, ah + 4)

    if not nacp_sz:
        raise SystemExit("this NRO has no embedded NACP (built without --nacp)")

    return d[ah + nacp_off: ah + nacp_off + nacp_sz], _ico_sz


def cstr(b):
    return b.split(b"\x00")[0].decode("utf-8", "replace")


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else "SafeShutdown.nro"
    n, ico_sz = read_nacp(path)
    print("file      :", path)
    print("icon size :", ico_sz)
    print("name      :", cstr(n[0x0000:0x0200]))
    print("author    :", cstr(n[0x0200:0x0300]))
    print("version   :", cstr(n[0x3060:0x3070]))


if __name__ == "__main__":
    main()
